"""Render the STUDIO drum kit offline (float DSP) and write it as 8-bit tables for Mozzi.

Usage: .venv/bin/python tools/gen_drums.py   →  src/drum_samples.h (+ tools/drums_preview.wav)

Every sound is synthesized here, so the kit is ours (no licensing issue).
Each table is peak-normalized to use all 8 bits, like the drum machines of the 80s.
"""
import wave
from pathlib import Path

import numpy as np

RATE = 32768          # = Mozzi AUDIO_RATE on ESP32
CELLS = 16384         # every table has the same length (0.5 s) → one Sample type in C++
ROOT = Path(__file__).resolve().parent.parent
rng = np.random.default_rng(42)
t = np.arange(CELLS) / RATE


def env(decay_s, attack_s=0.0005):
    a = np.clip(t / attack_s, 0, 1)
    return a * np.exp(-t / decay_s)


def sweep(f_start, f_end, time_s):
    """Exponential pitch drop: the 'boom' of a kick or a tom."""
    f = f_end + (f_start - f_end) * np.exp(-t / time_s)
    return np.sin(2 * np.pi * np.cumsum(f) / RATE)


def highpass(x, fc):
    a = np.exp(-2 * np.pi * fc / RATE)
    y = np.zeros_like(x)
    prev_x = prev_y = 0.0
    for i, v in enumerate(x):
        prev_y = a * (prev_y + v - prev_x)
        prev_x = v
        y[i] = prev_y
    return y


def lowpass(x, fc):
    a = np.exp(-2 * np.pi * fc / RATE)
    y = np.zeros_like(x)
    acc = 0.0
    for i, v in enumerate(x):
        acc = (1 - a) * v + a * acc
        y[i] = acc
    return y


def noise():
    return rng.uniform(-1, 1, CELLS)


def metal():
    """TR-808 cymbal/hat source: 6 detuned square waves (inharmonic, 'metallic')."""
    freqs = [205.3, 304.4, 369.6, 522.7, 540.0, 800.0]
    return sum(np.sign(np.sin(2 * np.pi * f * t)) for f in freqs) / 6


def kick():
    body = sweep(170, 48, 0.035) * env(0.32)
    click = highpass(noise(), 2000) * env(0.003) * 0.6
    return np.tanh(2.2 * (body + click))           # saturation = punch


def snare():
    tone = (np.sin(2 * np.pi * 185 * t) + 0.6 * np.sin(2 * np.pi * 330 * t)) * env(0.06)
    rattle = highpass(lowpass(noise(), 9000), 1500) * env(0.16)
    return np.tanh(1.6 * (0.7 * tone + rattle))


def hat(decay):
    src = highpass(metal() + 0.25 * noise(), 6000)
    return src * env(decay)


def clap():
    burst = np.zeros(CELLS)
    for k, start in enumerate((0.0, 0.011, 0.022, 0.034)):
        e = np.where(t >= start, np.exp(-(t - start) / (0.006 if k < 3 else 0.14)), 0)
        burst += e
    src = highpass(lowpass(noise(), 5000), 900)
    return src * burst


def tom(freq):
    body = sweep(freq * 1.4, freq, 0.05) * env(0.28)
    return np.tanh(1.5 * (body + 0.08 * noise() * env(0.02)))


SOUNDS = {                                  # order = TR_KICK … TR_TOML in audio.cpp
    "KICK": kick(), "SNARE": snare(), "HAT": hat(0.045), "OHAT": hat(0.32),
    "CLAP": clap(), "TOMH": tom(220), "TOMM": tom(160), "TOML": tom(110),
}


def to_int8(x):
    x = x / np.max(np.abs(x))                  # use the full 8 bits
    tail = np.argmax(np.abs(x[::-1]) > 1 / 256)
    x[CELLS - tail:] = 0                       # true silence at the end (no DC hum)
    return np.clip(np.round(x * 127), -127, 127).astype(np.int8)


def main():
    tables = {name: to_int8(snd) for name, snd in SOUNDS.items()}
    out = ["// Generated by tools/gen_drums.py — do not edit by hand.",
           "// STUDIO kit: 8 drum sounds rendered offline, 8-bit, 32768 Hz, 16384 cells (0.5 s).",
           "#pragma once", "#include <stdint.h>", "",
           f"#define DRUM_CELLS {CELLS}", ""]
    for name, tab in tables.items():
        body = ",".join(str(v) for v in tab.tolist())
        out.append(f"static const int8_t DRUM_{name}[DRUM_CELLS] __attribute__((aligned(4))) = {{{body}}};")
    out.append("static const int8_t* const DRUM_TABLES[8] = {" +
               ", ".join(f"DRUM_{n}" for n in tables) + "};")
    (ROOT / "src" / "drum_samples.h").write_text("\n".join(out) + "\n")

    preview = np.concatenate([tab.astype(np.int16) * 256 for tab in tables.values()])
    with wave.open(str(ROOT / "tools" / "drums_preview.wav"), "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(RATE)
        w.writeframes(preview.tobytes())
    print("wrote src/drum_samples.h and tools/drums_preview.wav")


if __name__ == "__main__":
    main()
