"""Generate src/ui/font_data.h from tools/fonts_src.py.

Usage: python3 tools/gen_fonts.py
"""
from pathlib import Path
from fonts_src import FONTS

OUT = Path(__file__).resolve().parent.parent / "src" / "ui" / "font_data.h"


def glyph_line(ch, rows):
    width = len(rows[0])
    bits = []
    for row in rows:
        b = 0
        for x, p in enumerate(row):
            if p == "#":
                b |= 0x80 >> x          # MSB = leftmost pixel
        bits.append(f"0x{b:02X}")
    bits += ["0x00"] * (7 - len(bits))
    c = "'\\''" if ch == "'" else f"'{ch}'"
    return f"    {{{c}, {width}, {{{', '.join(bits)}}}}},"


def main():
    out = ["// AUTO-GENERATED by tools/gen_fonts.py from tools/fonts_src.py — do not edit by hand.",
           "#pragma once", '#include "fonts.h"', ""]
    for name, glyphs in FONTS.items():
        height = len(next(iter(glyphs.values())))
        out.append(f"static const Glyph {name}_GLYPHS[] = {{")
        out += [glyph_line(ch, rows) for ch, rows in glyphs.items()]
        out.append("};")
        out.append(f"const Font {name} = {{{height}, {len(glyphs)}, {name}_GLYPHS}};")
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
